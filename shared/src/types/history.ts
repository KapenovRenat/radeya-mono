/**
 * История изменений: что поменялось у сущности, кто, когда и откуда.
 *
 * Лежит в той же таблице, что и журнал действий (`AuditLog`), — отличается
 * заполненным `changes`. Одна запись — одно событие: переименовали товар
 * и поменяли закупку одной формой — одна запись с двумя строками в `changes`.
 */

/** Одно изменённое поле. Значения строками: поля разного типа, а история только показывается. */
export interface HistoryChange {
  /** Ключ из HISTORY_FIELD_LABELS, подпись — через historyFieldLabel(). */
  field: string;
  /** null — значения не было. */
  from: string | null;
  to: string | null;
}

/**
 * Обстоятельства изменения. Поля известны заранее, а не свободный словарь:
 * иначе один модуль напишет `warehouse`, другой `store`, и по складу
 * историю будет не отфильтровать.
 */
export interface HistoryContext {
  /** Код склада: `PP3`. Для полей склада — остатка, резерва, срока предзаказа. */
  warehouse?: string;
  /** Номер документа: `03009`. */
  document?: string;
  /** Лист книги, из которой пришёл импорт. */
  sheet?: string;
  /** Пояснение, почему изменилось: «нет в отчёте — остаток обнулён». */
  note?: string;
}
