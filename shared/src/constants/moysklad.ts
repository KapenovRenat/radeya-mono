import { CURRENCIES, type Currency } from './currencies';

/**
 * Разбор выгрузки товаров МойСклада.
 *
 * Выгрузка — это весь справочник номенклатуры: товары, услуги, комплекты
 * и строки-заказы. Импорт берёт из неё три вещи, которых нет в Kaspi:
 * закупочную цену с валютой, поставщика и сроки предзаказа по складам.
 */

/**
 * Типы строк, которые едут в каталог.
 *
 * Услуги, комплекты и карточки контента товаром не являются: у них нет
 * ни закупки, ни склада, и в каталоге им делать нечего.
 */
export const MOYSKLAD_GOODS_TYPES = ['Товар', 'Модификация'] as const;

/**
 * Валюта закупки так, как её пишет МойСклад.
 *
 * Сопоставление списком, а не разбором строки: незнакомое название валюты
 * должно стать замечанием, а не молча превратиться в тенге.
 */
export const MOYSKLAD_CURRENCIES: Record<string, Currency> = {
  'тенге': CURRENCIES.KZT,
  'kzt': CURRENCIES.KZT,
  'руб': CURRENCIES.RUB,
  'rub': CURRENCIES.RUB,
};

/**
 * Колонка выгрузки → код нашего склада.
 *
 * В файле склады разложены по отдельным колонкам «Доп. поле: Склад N»,
 * и в ячейке лежит срок предзаказа в днях. Раскладка задана явно, а не
 * подбором по названию: склады у нас называются «Склад Астана», а в файле
 * «Доп. поле: Склад Астана», и совпадение по подстроке однажды свяжет
 * не тот склад.
 *
 * Склада Алматы у нас нет, и колонка `CA` пуста во всей выгрузке —
 * поэтому её здесь и нет. Появится склад — добавится строка.
 *
 * Название рядом с кодом не для красоты: `Warehouse.name` заполняет человек,
 * выгрузка Kaspi названий не содержит, и в справочнике они пустые. Импорт
 * проставляет их тем складам, у которых названия ещё нет, — здесь они
 * единственное место в системе, где написаны словами.
 */
export const MOYSKLAD_WAREHOUSE_COLUMNS: Record<string, { code: string; name: string }> = {
  'Доп. поле: Склад Астана': { code: 'PP3', name: 'Склад Астана' },
  'Доп. поле: Склад Павлодар': { code: 'PP6', name: 'Склад Павлодар' },
  'Доп. поле: Склад Костанай': { code: 'PP27', name: 'Склад Костанай' },
  'Доп. поле: Склад Петропавловск': { code: 'PP4', name: 'Склад Петропавловск' },
};

/** Колонки складов, которые импорт сознательно не использует. */
export const MOYSKLAD_IGNORED_WAREHOUSE_COLUMNS = ['Доп. поле: Склад Алматы'];

/**
 * Предел правдоподобного срока предзаказа в днях.
 *
 * В выгрузке встречаются значения от 7 до 20. Всё, что больше, скорее опечатка
 * или не тот столбец: срок предзаказа уходит на площадку, и трёхзначное число
 * там означало бы, что товар едет год.
 */
export const MOYSKLAD_MAX_PREORDER_DAYS = 180;

/** Сколько строк принимает запись за один вызов. */
export const MOYSKLAD_IMPORT_MAX_ROWS = 5000;

/**
 * Отчёт «Остатки» МойСклада.
 *
 * Отчёт строится на один склад: склада в нём нет ни колонкой, ни строкой,
 * поэтому склад выбирает человек при импорте. Название файла роли не играет.
 */

/**
 * Часовой пояс времени «на момент:» в шапке отчёта — Астана, UTC+5.
 *
 * Решение пользователя: вся система работает по времени Астаны. В проверенном
 * файле время на 2 часа меньше, чем на экране МойСклада (похоже на московское),
 * но для остатков это 0,08 дня в «днях на складе» — сверять не стали.
 */
export const MOYSKLAD_REPORT_UTC_OFFSET_HOURS = 5;

/**
 * Предел правдоподобного количества на складе, по модулю. Мебель штучная:
 * шестизначный остаток — это не тот столбец, а не склад.
 */
export const MOYSKLAD_MAX_STOCK_QUANTITY = 100_000;

/**
 * Предел «дней на складе». В проверенном отчёте максимум около 313 дней;
 * десять лет — заведомо не то число, и от него дата поступления уехала бы в прошлое века.
 */
export const MOYSKLAD_MAX_DAYS_ON_STOCK = 3650;
