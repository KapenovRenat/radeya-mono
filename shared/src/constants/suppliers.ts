/**
 * Поставщики и импорт их из выгрузки контрагентов МойСклада.
 *
 * Выгрузка — это **весь** справочник контрагентов: покупатели Kaspi, банки,
 * площадки и поставщики в одной книге. Поставщиками считаются только строки
 * своей группы; остальное не угадывается по типу или названию, а отбрасывается.
 */

/**
 * Группа контрагентов, строки которой импорт считает поставщиками.
 *
 * Отбор именно по группе, а не по «Тип контрагента»: в выгрузке и поставщики,
 * и покупатели помечены «Юридическое лицо», и по типу они неотличимы.
 * Группу проставляет человек в МойСкладе — это и есть его решение,
 * какой контрагент поставщик.
 */
export const SUPPLIER_IMPORT_GROUP = 'поставщики';

/**
 * Разделители пути групп в выгрузке: `поставщики/Казахстан`, `а, б`.
 *
 * Контрагент может лежать во вложенной группе, и тогда в ячейке путь целиком.
 * Сравниваем каждый кусок отдельно, иначе вложенный поставщик не найдётся.
 */
export const SUPPLIER_GROUP_SEPARATORS = /[/,;]/;

export const SUPPLIER_NAME_MAX_LENGTH = 200;
export const SUPPLIER_ADDRESS_MAX_LENGTH = 500;
export const SUPPLIER_PHONE_MAX_LENGTH = 100;

/** Идентификатор чата Telegram — число до 64 бит либо `@username`. */
export const SUPPLIER_TELEGRAM_ID_MAX_LENGTH = 64;

/**
 * Сколько строк принимает запись за один вызов.
 *
 * Поставщиков десятки, а не тысячи. Лимит нужен не ради скорости, а чтобы
 * случайно отправленный клиентский массив на сотню тысяч строк отклонялся
 * до транзакции, а не в середине неё.
 */
export const SUPPLIER_IMPORT_MAX_ROWS = 1000;
