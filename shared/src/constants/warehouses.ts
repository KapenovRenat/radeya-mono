/**
 * Справочник складов: склады Kaspi приходят из выгрузки, наши склады без Kaspi
 * (шоурум в ТЦ) заводятся руками.
 */

/** Код склада Kaspi: `PP3`. Такие коды заводит только выгрузка. */
export const WAREHOUSE_KASPI_CODE_PATTERN = /^PP\d{1,4}$/;

/**
 * Код нашего склада задаёт человек: латиница, цифры, `_` и `-`, первая — буква.
 * Код вида `PPn` под это правило подходит, поэтому проверяется отдельно —
 * иначе выгрузка Kaspi потом приняла бы наш склад за свой.
 */
export const WAREHOUSE_OWN_CODE_PATTERN = /^[A-Z][A-Z0-9_-]{1,15}$/;

export const WAREHOUSE_NAME_MAX_LENGTH = 150;
