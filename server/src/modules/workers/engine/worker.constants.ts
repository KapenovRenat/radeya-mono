export const HEARTBEAT_STALE_MS = 2 * 60_000;

/** Как часто выключенный или ждущий воркер перечитывает настройки. */
export const SETTINGS_POLL_MS = 15_000;

/** Потолок одного цикла. Дольше — цикл прерывается, следующий по расписанию. */
export const WORKER_RUN_TIMEOUT_MS = 10 * 60_000;

/** Запас блокировки поверх потолка цикла: прерванной работе нужно время закончить запрос. */
export const LOCK_HOLD_MARGIN_MS = 2 * 60_000;

/** Пауза после неожиданного сбоя самого цикла (например, база недоступна). */
export const LOOP_ERROR_PAUSE_MS = 30_000;

/** После скольких ошибок подряд оповещать разработчика. Одна ошибка — не повод будить. */
